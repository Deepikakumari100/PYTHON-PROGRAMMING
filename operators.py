# Membership Operters(in & not in)
s='heiio'
print('p' not in s)

l=[10,20,30,78,50]
print(10 in l)

# Identity Opertors(is & is not)    is i,e == & is not i,e !=
x=10
y=10
print(x is y)
print(x is not y)

# Bitwise Opertors(&[AND],|[OR],^[XOR])
a=10
b=8
print(bin(a))
print(bin(b))
print(bin(a&b),a&b)
print(bin(a|b),a|b)
print(bin(a^b),a^b)